using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace eQuantic.UI.Generators;

/// <summary>
/// Reads <c>ui.UseContentSecurityPolicy(…)</c> out of the app's own source and writes
/// <c>[assembly: ContentSecurityPolicy]</c> (#1269), the way the native capabilities reach the build:
/// the app states the policy once, in <c>Program.cs</c>, and the build learns of it without a setting
/// of its own. eqc reads the attribute and refuses the escape hatch's inline handlers, which a strict
/// policy refuses in the browser.
/// </summary>
[Generator]
public sealed class ContentSecurityPolicyGenerator : IIncrementalGenerator
{
    private const string OptionsType = "eQuantic.UI.Server.UIOptions";
    private const string Method = "UseContentSecurityPolicy";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declared = context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, _) => node is InvocationExpressionSyntax
                {
                    Expression: MemberAccessExpressionSyntax { Name.Identifier.ValueText: Method }
                        or IdentifierNameSyntax { Identifier.ValueText: Method },
                },
                transform: static (ctx, token) =>
                    ctx.SemanticModel.GetOperation(ctx.Node, token) is IInvocationOperation invocation
                    && invocation.TargetMethod.Name == Method
                    && invocation.TargetMethod.ContainingType?.ToDisplayString() == OptionsType)
            .Where(static isPolicy => isPolicy)
            .Collect();

        context.RegisterSourceOutput(declared, static (spc, calls) =>
        {
            if (calls.IsDefaultOrEmpty) return;
            spc.AddSource("ContentSecurityPolicy.g.cs",
                "// <auto-generated/>\n"
                + "// The app calls UseContentSecurityPolicy, so its build refuses the escape hatch's inline handlers.\n"
                + "[assembly: global::eQuantic.UI.Server.ContentSecurityPolicy]\n");
        });
    }
}
