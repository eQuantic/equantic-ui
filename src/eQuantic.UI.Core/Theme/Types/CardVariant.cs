namespace eQuantic.UI.Core.Theme.Types;

/// <summary>
/// Card visual variants
/// </summary>
public enum CardVariant
{
    /// <summary>
    /// Default filled card with background
    /// </summary>
    Default,

    /// <summary>
    /// Card with border only, transparent background
    /// </summary>
    Outline,

    /// <summary>
    /// Card with prominent shadow and elevation
    /// </summary>
    Elevated,

    /// <summary>
    /// Subtle card with minimal visual weight
    /// </summary>
    Subtle,

    /// <summary>
    /// Ghost card with no background or border
    /// </summary>
    Ghost
}
