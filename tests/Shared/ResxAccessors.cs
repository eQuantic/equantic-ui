using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;

/// <summary>
/// The accessor class the SDK's build writes for a neutral <c>.resx</c> (#1784), for a test that compiles
/// a project's sources in memory, where no build runs: a template ships its <c>.resx</c> and no Designer.
/// Its shape is the one MSBuild's <c>GenerateResource</c> writes and the SDK's own targets are proven to
/// write (<c>ResourceAccessorsTests</c>): a static <c>ResourceManager</c> over the manifest name, a static
/// <c>Culture</c>, and one static string per key, its name the key with what no identifier may hold
/// turned into <c>_</c>.
/// </summary>
internal static class ResxAccessors
{
    /// <summary>The accessor class of <paramref name="resx"/>, in <paramref name="ns"/>, named by the file.</summary>
    public static string Source(string resx, string ns)
    {
        var name = Path.GetFileNameWithoutExtension(resx);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine($"namespace {ns};");
        source.AppendLine($"internal class {name}");
        source.AppendLine("{");
        source.AppendLine($"    private static global::System.Resources.ResourceManager? resourceMan;");
        source.AppendLine("    internal static global::System.Resources.ResourceManager ResourceManager =>");
        source.AppendLine($"        resourceMan ??= new global::System.Resources.ResourceManager(\"{ns}.{name}\", typeof({name}).Assembly);");
        source.AppendLine("    internal static global::System.Globalization.CultureInfo? Culture { get; set; }");
        foreach (var data in XDocument.Load(resx).Root!.Elements("data"))
        {
            var key = (string)data.Attribute("name")!;
            var property = Regex.Replace(key, @"[^\w]", "_");
            source.AppendLine($"    internal static string {property} => ResourceManager.GetString(\"{key}\", Culture)!;");
        }
        source.AppendLine("}");
        return source.ToString();
    }
}
